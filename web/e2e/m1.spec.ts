import {test,expect,chromium} from '@playwright/test';
import {readFile,mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import {parse} from 'yaml';
import {startFixture,until} from '../../tests/e2e/fixture.mjs';

const evidence=fileURLToPath(new URL('../../.local/evidence/',import.meta.url));
test('M1: persistent TLS Hub and two independent Agent processes',async()=>{
  const f=await startFixture();
  const browser=await chromium.launch({channel:process.env.DOCKROOM_BROWSER_CHANNEL||undefined,args:[`--ignore-certificate-errors-spki-list=${f.spki}`]}).catch(async e=>{await f.close();throw e;});
  try {
    const ids=f.pids();expect(new Set(ids).size).toBe(3);
    const reader=await f.login('reader');const other=await f.login('other');
    const schema=parse(await readFile(new URL('../../spec/openapi.yaml',import.meta.url),'utf8'));
    const ajv=new Ajv2020({strict:false,validateFormats:false});const defs={$id:'https://dockroom.test/openapi',components:schema.components};ajv.addSchema(defs);
    for(const name of ['Identity','Node','Root','Ref','Entry','Listing','Resolved','Failure'])
      expect(ajv.getSchema(`${defs.$id}#/components/schemas/${name}`)).toBeTruthy();
    function contract(name:string,data:unknown){const validate=ajv.getSchema(`${defs.$id}#/components/schemas/${name}`)!;expect(validate(data),JSON.stringify(validate.errors)).toBe(true);}
    const c = new Ajv2020({validateFormats:false});const control=c.compile(JSON.parse(await readFile(new URL('../../spec/control.schema.json',import.meta.url),'utf8')));
    const vectors=JSON.parse(await readFile(new URL('../../spec/fixtures/locator.json',import.meta.url),'utf8'));
    contract('Ref',vectors.windows.ref);contract('Ref',vectors.linux.ref);
    expect(control({major:1,minor:0,nodeId:'archive-01',os:'linux',version:'fixture',volumeCapability:'openat2',roots:[{rootId:'archive',label:'fixture',mode:'readOnly',binding:'a'.repeat(64)}]})).toBe(true);
    expect(control({major:2,minor:0,nodeId:'archive-01',os:'linux',version:'fixture',volumeCapability:'openat2',roots:[]})).toBe(false);
    const get=(path:string,s=reader)=>f.api(path,{session:s});
    const post=(path:string,body:unknown,s=reader)=>f.api(path,{method:'POST',session:s,body});
    const list=(i:number,parts:string[]=[],extra:Record<string,string>={},s=reader)=>post('/fs/list',{ref:f.ref(i,parts),...extra},s);
    contract('Identity',(await f.expect(get('/me'),200)).data);
    contract('Failure',(await f.expect(f.api('/nodes'),401)).data);
    const nodes=(await f.expect(get('/nodes'),200)).data;expect(nodes).toHaveLength(2);nodes.forEach(x=>contract('Node',x));
    expect((await f.expect(get('/nodes',other),200)).data.map(x=>x.nodeId)).toEqual(['studio-07']);
    await f.expect(get('/nodes/archive-01/roots',other),404);
    await f.expect(list(1,[],{},other),404);
    const rightRoots=(await f.expect(get('/nodes/archive-01/roots'),200)).data;expect(rightRoots[0].mode).toBe('readOnly');contract('Root',rightRoots[0]);
    await f.expect(f.api('/fs/list',{method:'POST',session:reader,body:{ref:f.ref(0)},headers:{Origin:'https://not-dockroom.invalid'}}),403);
    await f.expect(f.api('/fs/list',{method:'POST',session:reader,body:{ref:f.ref(0)},headers:{'X-CSRF-Token':'wrong'}}),403);
    await f.expect(post('/fs/mkdir',{ref:f.ref(0)}),404);
    await f.expect(post('/jobs',{},reader),422);
    const snapshot=(await f.expect(list(0),200)).data;contract('Listing',snapshot);
    expect(snapshot.entries.map(r=>r.name)).not.toContain('.dockroom');
    expect(snapshot.entries.find(r=>r.name==='目录链接')?.kind).toBe('unsupported');
    for(const part of ['目录链接','.dockroom','..','a/b','a\\b'])await f.expect(list(0,[part]),422);
    await f.expect(post('/fs/resolve',{ref:f.ref(0),input:f.paths[1]}),422);
    const loc=(await f.expect(post('/fs/resolve',{ref:f.ref(0),input:join(f.paths[0],f.sub[0])}),200)).data;contract('Resolved',loc);expect(loc.ref.parts).toEqual([f.sub[0]]);
    const empty=(await f.expect(list(1,[f.sub[1],'空目录']),200)).data;contract('Listing',empty);expect(empty.entries).toEqual([]);
    const initial=(await f.expect(list(0,['分页夹具']),200)).data;expect(initial.entries).toHaveLength(200);
    const tail=(await f.expect(list(0,['分页夹具'],{cursor:initial.nextCursor}),200)).data;expect(tail.listingId).toBe(initial.listingId);expect(tail.entries).toHaveLength(7);
    await f.expect(list(0,['分页夹具'],{cursor:initial.nextCursor},other),409);
    await f.expect(list(0,[],{cursor:initial.nextCursor}),409);
    await f.expect(list(0,['分页夹具'],{cursor:initial.nextCursor,filter:'different'}),409);
    expect((await f.expect(list(0,['分页夹具'],{filter:'206'}),200)).data.entries[0].name).toBe('fixture-206.txt');
    await f.grant('other',0,false);await f.expect(list(0,[],{},other),404);

    const page=await browser.newPage({viewport:{width:1440,height:900},permissions:['clipboard-read','clipboard-write']});
    page.setDefaultTimeout(7000);
    const pageErrors:Error[]=[];page.on('pageerror',e=>pageErrors.push(e));
    await page.goto(f.origin);await page.getByLabel('账号').fill('reader');await page.getByLabel('口令').fill(f.accounts.reader);await page.getByRole('button',{name:'登录',exact:true}).click();
    const left=page.getByRole('article',{name:'左栏目录'});const right=page.getByRole('article',{name:'右栏目录'});
    const host=(side:typeof left)=>side.getByRole('combobox',{name:'设备',exact:true});
    await expect(left.getByRole('button',{name:'打开 2026'})).toBeVisible();
    await expect(right.getByRole('button',{name:'打开 十一月'})).toBeVisible();
    await host(left).selectOption(f.nodes[0]);await expect(host(left)).toHaveValue(f.nodes[0]);
    await host(right).selectOption(f.nodes[1]);await expect(host(right)).toHaveValue(f.nodes[1]);
    const leftFolder=left.getByRole('button',{name:'打开 十一月'});await leftFolder.focus();await page.keyboard.press('Enter');
    await right.getByRole('button',{name:'打开 2026'}).click();
    await expect(left.getByText('封面 修订.tif',{exact:true})).toBeVisible();await expect(right.getByText('交接说明.txt',{exact:true})).toBeVisible();
    await left.getByRole('checkbox',{name:'选择 封面 修订.tif'}).check();
    await expect(left.getByText('已载入 5 项 · 已选 1 项')).toBeVisible();
    await left.getByRole('button',{name:'复制路径'}).click();expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(join(f.paths[0],f.sub[0]));
    await mkdir(evidence,{recursive:true});
    await page.screenshot({path:join(evidence,'m1-1440.png'),fullPage:true});
    await page.setViewportSize({width:1024,height:850});await page.screenshot({path:join(evidence,'m1-1024.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'左栏目录'}).click();await expect(left).toBeVisible();await expect(right).toBeHidden();
    await page.getByRole('button',{name:'右栏目录'}).click();await expect(right.getByText('交接说明.txt')).toBeVisible();await page.screenshot({path:join(evidence,'m1-390.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:900});
    await right.getByRole('button',{name:'打开 空目录'}).click();await expect(right.getByText('此目录为空')).toBeVisible();
    await right.getByRole('button',{name:'后退'}).click();await expect(right.getByText('交接说明.txt')).toBeVisible();
    await left.getByLabel('原生绝对路径').fill(join(f.paths[0],'分页夹具'));await left.getByRole('button',{name:'定位'}).click();
    await left.getByRole('button',{name:'加载下一页'}).click();await expect(left.getByText('已载入 207 项')).toBeVisible();
    await left.getByLabel('按名称筛选').fill('206');await expect(left.getByText('fixture-206.txt')).toBeVisible();await expect(left.getByText('fixture-000.txt')).toHaveCount(0);
    await host(left).selectOption(f.nodes[1]);await host(right).selectOption(f.nodes[0]);
    await expect(left.getByRole('button',{name:'打开 2026'})).toBeVisible();await expect(right.getByRole('button',{name:'打开 十一月'})).toBeVisible();
    await page.reload();await expect(host(left)).toHaveValue(f.nodes[1]);await expect(host(right)).toHaveValue(f.nodes[0]);
    await f.stopAgent(1);await expect(left.getByText('设备离线',{exact:true})).toBeVisible();await expect(left.getByRole('table')).toHaveCount(0);
    await expect(right.getByRole('button',{name:'打开 十一月'})).toBeVisible();await page.screenshot({path:join(evidence,'m1-offline.png'),fullPage:true});
    await f.expect(list(1),503);f.startAgent(1);
    await until(async()=>(await list(1)).status===200);await expect(left.getByRole('button',{name:'打开 2026'})).toBeVisible();
    await f.restartHub();await until(async()=>(await get('/nodes')).data.filter(n=>n.online).length===2);await f.expect(list(0),200);
    await f.stopAgent(1);
    await until(async()=>(await get('/admin/nodes',f.admin)).data.some(n=>n.nodeId===f.nodes[1]&&!n.online));
    await f.repinUnderSameID(1);f.startAgent(1);
    await until(async()=>(await get('/admin/nodes',f.admin)).data.some(n=>n.nodeId===f.nodes[1]&&n.online));
    await f.expect(list(1),404);await f.expect(get('/nodes/archive-01/roots'),404);
    await f.expect(f.api(`/nodes/${f.nodes[1]}/revoke`,{method:'POST',session:f.admin}),204);
    await f.expect(list(1),404);
    expect((await f.expect(get('/admin/nodes',f.admin),200)).data.find(n=>n.nodeId===f.nodes[1])).toMatchObject({state:'revoked',online:false});
    await page.getByRole('button',{name:'退出'}).click();await expect(page.getByRole('button',{name:'登录',exact:true})).toBeVisible();
    expect(pageErrors).toEqual([]);console.log(`M1 fixture: Hub PID ${ids[0]}, two Agent PIDs ${ids[1]}, ${ids[2]}; paging 200+7; OS ${process.platform}; screenshots in .local/evidence`);
  }finally{await browser.close();await f.close();}
});
